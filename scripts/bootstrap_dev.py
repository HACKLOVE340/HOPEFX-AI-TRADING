def _load_env() -> None:
    """Load .env into os.environ (idempotent)."""
    os.environ.setdefault("APP_ENV", "development")
    os.environ.setdefault("DATABASE_URL", f"sqlite:///{_DB_URL_PATH}")
    try:
        from dotenv import load_dotenv

        load_dotenv(ENV_PATH, override=False)
    except ImportError:
        for _line in ENV_PATH.read_text().splitlines():
            line = _line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, _, v = line.partition("=")
                os.environ.setdefault(k.strip(), v.strip())
    os.environ.setdefault("SECURITY_JWT_SECRET", secrets.token_urlsafe(48))


def _make_engine():
    from sqlalchemy import create_engine

    db_url = os.environ.get("DATABASE_URL", f"sqlite:///{DB_PATH}")
    connect_args = {"check_same_thread": False} if db_url.startswith("sqlite") else {}
    return create_engine(db_url, connect_args=connect_args)


def _seed_user(email: str, username: str, password: str, role_value: str) -> None:
    """Upsert a single user. Creates tables if needed."""
    import uuid
    from sqlalchemy.orm import sessionmaker
    from auth.service import hash_password
    from database.models import Base
    from database.user_models import User, UserStatus

    engine = _make_engine()
    Base.metadata.create_all(engine, checkfirst=True)
    Session = sessionmaker(bind=engine)
    session = Session()
    try:
        existing = session.query(User).filter_by(email=email).first()
        if existing:
            changed = False
            if existing.role != role_value:
                existing.role = role_value
                changed = True
            # Resync password in case .env was regenerated with a new value
            from auth.service import verify_password as _vp
            if not _vp(password, existing.hashed_password):
                existing.hashed_password = hash_password(password)
                existing.status = "active"
                existing.is_email_verified = True
                changed = True
            if changed:
                session.commit()
            return
        user = User(
            id=str(uuid.uuid4()),
            email=email,
            username=username,
            hashed_password=hash_password(password),
            role=role_value,
            status=UserStatus.ACTIVE.value,
            is_email_verified=True,
        )
        session.add(user)
        session.commit()
    finally:
        session.close()


