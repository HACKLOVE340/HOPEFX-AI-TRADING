def build_frontend(verbose: bool = True) -> bool:
    """Build the React frontend into static/ if not already built.

    Idempotent — skips the build when static/index.html already exists.
    Returns True if the build ran (or was already present), False on failure.
    """
    import shutil
    import subprocess

    static_index = ROOT / "static" / "index.html"
    frontend_dir = ROOT / "frontend"

    if static_index.exists():
        if verbose:
            logger.info("  Frontend already built  ->  static/")
        return True

    if not (frontend_dir / "package.json").exists():
        if verbose:
            logger.warning("  frontend/package.json not found — skipping frontend build")
        return False

    npm = shutil.which("npm")
    if not npm:
        if verbose:
            logger.warning("  npm not found — skipping frontend build (install Node.js 20+)")
        return False

    if verbose:
        logger.info("  Building frontend (npm install && npm run build)...")

    try:
        # Install deps only if node_modules is absent or package-lock changed
        node_modules = frontend_dir / "node_modules"
        if not node_modules.exists():
            subprocess.run(
                [npm, "install", "--silent"],
                cwd=str(frontend_dir),
                check=True,
                timeout=300,
            )

        subprocess.run(
            [npm, "run", "build"],
            cwd=str(frontend_dir),
            check=True,
            timeout=300,
        )

        if verbose:
            logger.info("  Frontend built  ->  static/")
        return True

    except subprocess.CalledProcessError as exc:
        if verbose:
            logger.warning("  Frontend build failed (non-fatal): %s", exc)
        return False
    except subprocess.TimeoutExpired:
        if verbose:
            logger.warning("  Frontend build timed out after 5 minutes")
        return False


def bootstrap(verbose: bool = True) -> None:
    created = _generate_env()

    if verbose:
        logger.info("\n" + "-" * 62)
        logger.info("  HOPEFX Dev Bootstrap")
        logger.info("-" * 62)
        if created:
            logger.info(f"  Generated .env  ->  {ENV_PATH}")
        else:
            logger.info(f"  .env already exists  ->  {ENV_PATH}")

    for seed_fn, label, email, _username, redirect in [
        (_seed_superadmin, "Superadmin", DEFAULT_SUPERADMIN_EMAIL, DEFAULT_SUPERADMIN_USERNAME, "/superadmin"),
        (_seed_admin, "Admin", DEFAULT_ADMIN_EMAIL, DEFAULT_ADMIN_USERNAME, "/admin"),
        (_seed_trader, "Trader", DEFAULT_TRADER_EMAIL, DEFAULT_TRADER_USERNAME, "/dashboard"),
    ]:
        try:
            seed_fn()
            if verbose:
                logger.info(f"  {label} seeded  ({email}  ->  {redirect})")
        except Exception as exc:  # pylint: disable=broad-exception-caught
            if verbose:
                logger.warning(f"  {label} seed skipped: {exc}")

    build_frontend(verbose=verbose)

    if verbose:
        logger.info("-" * 62)
        logger.info("  Start the server:  python app.py")
        logger.info("  Login at:          http://localhost:8000/login")
        logger.info("-" * 62 + "\n")


if __name__ == "__main__":
    bootstrap(verbose=True)
