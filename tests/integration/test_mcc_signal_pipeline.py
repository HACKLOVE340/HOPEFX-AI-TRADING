def _make_mcc(broker=None):
    """Return a fresh MasterControlCore with an optional BrokerManager attached."""
    from core.mcc.master_control import MasterControlCore, MCCConfig

    mcc = MasterControlCore(MCCConfig(max_strategies_active=5))
    if broker is not None:
        # Inject broker manager so _execute_signal() can reach it without the
        # full app startup sequence.
        from brokers.manager import BrokerManager

        mgr = BrokerManager(primary_broker_name="test_broker")
        mgr.register("test_broker", broker)
        mgr.set_active("test_broker")

        # Patch get_broker_manager so the MCC lazy-import returns our instance.
        mcc._injected_broker_manager = mgr  # saved for reference
    return mcc


def _patch_get_broker_manager(mgr):
    """Context manager that patches get_broker_manager to return mgr."""
    return patch(
        "core.startup_factories.get_broker_manager",
        return_value=mgr,
    )


def _make_paper_broker(balance: float = 100_000.0):
    from brokers.paper_trading import PaperTradingBroker

    return PaperTradingBroker(initial_balance=balance)


def _make_strategy(name: str, action: str = "BUY", confidence: float = 0.85):
    """Return a minimal strategy-like object compatible with MCC."""
    from strategies.base_enhanced import EnhancedStrategy, StrategyConfig, StrategySignal

    config = StrategyConfig(name=name, max_position_size=Decimal("0.10"))
    strategy = EnhancedStrategy(config=config)

    # Monkey-patch on_price to emit a signal immediately
    original_price = strategy.on_price

    def _emit_signal(ts, price, bid=None, ask=None):
        original_price(ts, price, bid, ask)
        if strategy.mcc_callback:
            sig = StrategySignal(
                action=action,
                strength=0.8,
                confidence=confidence,
                symbol="XAU_USD",
            )
            strategy.mcc_callback(name, sig)

    strategy.on_price = _emit_signal
    return strategy


