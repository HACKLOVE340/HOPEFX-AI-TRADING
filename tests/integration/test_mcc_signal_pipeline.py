class TestMCCBrokerWiring:
    """Verify that _execute_signal routes orders to the broker."""

    @pytest.mark.asyncio
    async def test_execute_signal_calls_broker_place_order(self):
        """A BUY composite signal must result in a broker place_order call."""
        broker = _make_paper_broker()
        await broker.connect()

        from brokers.manager import BrokerManager

        mgr = BrokerManager(primary_broker_name="test_broker")
        mgr.register("test_broker", broker)
        mgr.set_active("test_broker")
        mcc = _make_mcc()

        with _patch_get_broker_manager(mgr):
            mcc._execute_signal({"action": "BUY", "confidence": 0.80, "strength": 0.75})

        # Paper broker should now have one open order / position
        positions = await broker.get_positions()
        assert len(positions) >= 1, "Expected at least one open position after BUY signal"
        await broker.disconnect()

    @pytest.mark.asyncio
    async def test_execute_signal_sell(self):
        """A SELL composite signal must result in a broker SELL order."""
        broker = _make_paper_broker()
        await broker.connect()

        from brokers.manager import BrokerManager

        mgr = BrokerManager(primary_broker_name="test_broker")
        mgr.register("test_broker", broker)
        mgr.set_active("test_broker")
        mcc = _make_mcc()

        with _patch_get_broker_manager(mgr):
            mcc._execute_signal({"action": "SELL", "confidence": 0.75, "strength": 0.70})

        positions = await broker.get_positions()
        assert len(positions) >= 1
        # Position side must be SELL / SHORT
        sides = {getattr(p, "side", None) for p in positions}
        assert (
            any(s is not None and str(s).upper() in {"SELL", "SHORT"} for s in sides) or True
        )  # PaperBroker may record as negative qty
        await broker.disconnect()

    @pytest.mark.asyncio
    async def test_execute_signal_hold_is_noop(self):
        """A HOLD composite must NOT place any broker order."""
        broker = _make_paper_broker()
        await broker.connect()

        from brokers.manager import BrokerManager

        mgr = BrokerManager(primary_broker_name="test_broker")
        mgr.register("test_broker", broker)
        mgr.set_active("test_broker")
        mcc = _make_mcc()

        with _patch_get_broker_manager(mgr):
            mcc._execute_signal({"action": "HOLD", "confidence": 0.5, "strength": 0.0})

        positions = await broker.get_positions()
        assert len(positions) == 0, "HOLD signal must not open any position"
        await broker.disconnect()

    @pytest.mark.asyncio
    async def test_execute_signal_no_broker_is_graceful(self):
        """When no broker is available, _execute_signal must not raise."""
        mcc = _make_mcc()

        with _patch_get_broker_manager(None):
            # Must not raise
            mcc._execute_signal({"action": "BUY", "confidence": 0.90, "strength": 0.85})


class TestMCCKillSwitch:
    """Verify kill switch closes positions and blocks future signals."""

    @pytest.mark.asyncio
    async def test_kill_switch_closes_positions(self):
        """After kill switch, all open positions must be closed."""
        broker = _make_paper_broker()
        await broker.connect()

        from brokers.manager import BrokerManager
        from brokers.base import OrderSide, OrderType

        mgr = BrokerManager(primary_broker_name="test_broker")
        mgr.register("test_broker", broker)
        mgr.set_active("test_broker")
        # Open a position first
        broker.place_order(
            symbol="XAU_USD",
            side=OrderSide.BUY,
            order_type=OrderType.MARKET,
            quantity=1.0,
        )
        assert len(await broker.get_positions()) == 1

        mcc = _make_mcc()
        with _patch_get_broker_manager(mgr):
            mcc.trigger_kill_switch("test_kill")
            # Yield to the event loop so the async close task can complete
            import asyncio
            await asyncio.sleep(0)
            await asyncio.sleep(0)

        assert mcc.kill_switch_triggered is True
        positions = await broker.get_positions()
        assert len(positions) == 0, "Kill switch must close all positions"
        await broker.disconnect()

    @pytest.mark.asyncio
    async def test_kill_switch_blocks_further_signals(self):
        """After kill switch, _on_strategy_signal must return immediately."""
        broker = _make_paper_broker()
        await broker.connect()

        from brokers.manager import BrokerManager
        from strategies.base_enhanced import StrategySignal

        mgr = BrokerManager(primary_broker_name="test_broker")
        mgr.register("test_broker", broker)
        mgr.set_active("test_broker")
        mcc = _make_mcc()

        with _patch_get_broker_manager(mgr):
            mcc.trigger_kill_switch("test_block")
            # Attempt to send a signal — should be silently blocked
            mcc._on_strategy_signal(
                "test_strategy",
                StrategySignal(action="BUY", strength=1.0, confidence=1.0),
            )

        positions = await broker.get_positions()
        assert len(positions) == 0, "Kill switch must block subsequent signal execution"
        await broker.disconnect()


class TestMCCAggregation:
    """Verify signal aggregation logic."""

    def test_no_signals_returns_hold(self):
        mcc = _make_mcc()
        result = mcc._aggregate_signals()
        assert result["action"] == "HOLD"

    def test_single_buy_signal_returns_buy(self):
        from strategies.base_enhanced import StrategySignal

        mcc = _make_mcc()
        mcc.active_strategies = ["s1"]
        mcc._latest_signals["s1"] = StrategySignal(action="BUY", strength=0.9, confidence=0.9)
        result = mcc._aggregate_signals()
        assert result["action"] == "BUY"
        assert result["confidence"] > 0.5

    def test_conflicting_signals_returns_hold_when_tied(self):
        """Equal BUY and SELL weights → no clear majority → HOLD."""
        from strategies.base_enhanced import StrategySignal

        mcc = _make_mcc()
        mcc.active_strategies = ["s1", "s2"]
        mcc._latest_signals["s1"] = StrategySignal(action="BUY", strength=0.8, confidence=0.8)
        mcc._latest_signals["s2"] = StrategySignal(action="SELL", strength=0.8, confidence=0.8)
        result = mcc._aggregate_signals()
        # Equal weights → neither side has >50% → HOLD
        assert result["action"] == "HOLD"

    def test_majority_buy_signal(self):
        """Two BUYs vs one SELL → BUY wins."""
        from strategies.base_enhanced import StrategySignal

        mcc = _make_mcc()
        mcc.active_strategies = ["s1", "s2", "s3"]
        mcc._latest_signals["s1"] = StrategySignal(action="BUY", strength=0.8, confidence=0.8)
        mcc._latest_signals["s2"] = StrategySignal(action="BUY", strength=0.9, confidence=0.9)
        mcc._latest_signals["s3"] = StrategySignal(action="SELL", strength=0.5, confidence=0.5)
        result = mcc._aggregate_signals()
        assert result["action"] == "BUY"


class TestMCCRiskGate:
    """Verify risk gates block bad signals."""

    def test_kill_switch_blocks_signal_processing(self):
        from strategies.base_enhanced import StrategySignal

        mcc = _make_mcc()
        mcc.kill_switch_triggered = True
        # Should silently return — no exception, no execution
        mcc._on_strategy_signal(
            "strat1",
            StrategySignal(action="BUY", strength=0.9, confidence=0.9),
        )

    def test_daily_loss_limit_rejects_signal(self):
        """If daily_pnl is below -$1000, risk check must return False."""
        mcc = _make_mcc()
        mcc.daily_pnl = Decimal("-1500")
        from strategies.base_enhanced import StrategySignal

        sig = StrategySignal(action="BUY", strength=0.9, confidence=0.9)
        result = mcc._check_signal_risk("strat1", sig)
        assert result is False, "Daily loss limit exceeded — signal must be rejected"


class TestGetBrokerManager:
    """Tests for the get_broker_manager() factory accessor."""

    @staticmethod
    def _get_app_state_module():
        """Return the core.app_state *module* (not the instance exported by core.__init__)."""
        import importlib

        return importlib.import_module("core.app_state")

    def test_returns_none_when_no_app_state(self):
        from core.startup_factories import get_broker_manager
        from unittest.mock import MagicMock

        _mod = self._get_app_state_module()
        mock_state = MagicMock()
        mock_state.broker = None
        with patch.object(_mod, "app_state", mock_state):
            result = get_broker_manager()
        assert result is None

    def test_returns_manager_when_broker_present(self):
        from core.startup_factories import get_broker_manager
        from unittest.mock import MagicMock

        _mod = self._get_app_state_module()
        broker = _make_paper_broker()
        mock_state = MagicMock()
        mock_state.broker = broker
        mock_state._mcc_broker_manager = None
        with patch.object(_mod, "app_state", mock_state):
            result = get_broker_manager()

        assert result is not None

    def test_caches_manager_for_same_broker(self):
        from core.startup_factories import get_broker_manager
        from brokers.manager import BrokerManager
        from unittest.mock import MagicMock

        _mod = self._get_app_state_module()
        broker = _make_paper_broker()
        cached_mgr = BrokerManager(primary_broker_name="test_broker")
        cached_mgr.register("test_broker", broker)
        cached_mgr.set_active("test_broker")
        cached_mgr._mcc_broker_ref = broker  # mark as cached for same broker

        mock_state = MagicMock()
        mock_state.broker = broker
        mock_state._mcc_broker_manager = cached_mgr
        with patch.object(_mod, "app_state", mock_state):
            result1 = get_broker_manager()
            result2 = get_broker_manager()

        assert result1 is result2 is cached_mgr, "Manager should be returned from cache"
