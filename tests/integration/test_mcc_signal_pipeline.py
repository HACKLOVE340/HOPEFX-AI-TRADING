"""
tests/integration/test_mcc_signal_pipeline.py
==============================================
End-to-end integration tests for the MCC signal → gatekeeper → broker
execution pipeline.

These tests use the *real* ``MasterControlCore``, ``PaperTradingBroker``, and
``BrokerManager`` — no mocks or synthetic data.  They verify that:

1. Signals generated by strategies flow through the MCC aggregation and risk
   gates, and that a valid composite signal reaches the broker.
2. ``trigger_kill_switch()`` closes all open positions via the broker.
3. The ``get_broker_manager()`` factory properly returns a ``BrokerManager``
   backed by the ``AppState`` singleton broker.
4. Correlation guard correctly rejects correlated same-direction signals.
5. Kill switch blocks all further signal processing after activation.
"""

