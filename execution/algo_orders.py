class AlgoOrderManager:
    """
    Manages active algo orders and routes child fills.

    Provides a unified interface for submitting TWAP, VWAP, and Iceberg
    orders. Each algo runs in its own asyncio task.

    The manager also decides WHEN to use an algo vs a plain market order:
    - Orders > ALGO_LARGE_ORDER_THRESHOLD lots → use TWAP/VWAP
    - Orders > ALGO_ICEBERG_THRESHOLD lots → use Iceberg
    - Smaller orders → plain market order (no algo overhead)
    """

    # Thresholds for automatic algo selection (env-overridable)
    LARGE_ORDER_THRESHOLD: float = float(os.getenv("ALGO_LARGE_ORDER_THRESHOLD", "10.0"))
    ICEBERG_THRESHOLD: float = float(os.getenv("ALGO_ICEBERG_THRESHOLD", "50.0"))
    DEFAULT_TWAP_DURATION: float = float(os.getenv("ALGO_DEFAULT_TWAP_DURATION", "300"))
    DEFAULT_TWAP_SLICES: int = int(os.getenv("ALGO_DEFAULT_TWAP_SLICES", "10"))
    DEFAULT_ICEBERG_PEAK: float = float(os.getenv("ALGO_DEFAULT_ICEBERG_PEAK", "5.0"))

    def __init__(self, broker_submit_fn: Callable | None = None) -> None:
        self._broker_submit = broker_submit_fn
        self._active: dict[str, AlgoOrder] = {}
        self._completed: dict[str, AlgoFillReport] = {}
        self._tasks: dict[str, asyncio.Task] = {}

    def set_broker_submit_fn(self, fn: Callable) -> None:
        """Wire in the broker submission function after construction."""
        self._broker_submit = fn

    async def submit_twap(
        self,
        symbol: str,
        side: str,
        total_quantity: float,
        duration_seconds: float,
        num_slices: int = 10,
        strategy_id: str = "unknown",
    ) -> str:
        """Submit a TWAP order. Returns algo_id."""
        order = TWAPOrder(
            symbol=symbol,
            side=side,
            total_quantity=total_quantity,
            duration_seconds=duration_seconds,
            num_slices=num_slices,
            strategy_id=strategy_id,
            broker_submit_fn=self._broker_submit,
        )
        return await self._launch(order)

    async def submit_vwap(
        self,
        symbol: str,
        side: str,
        total_quantity: float,
        duration_seconds: float,
        num_slices: int = 20,
        strategy_id: str = "unknown",
    ) -> str:
        """Submit a VWAP order. Returns algo_id."""
        order = VWAPOrder(
            symbol=symbol,
            side=side,
            total_quantity=total_quantity,
            duration_seconds=duration_seconds,
            num_slices=num_slices,
            strategy_id=strategy_id,
            broker_submit_fn=self._broker_submit,
        )
        return await self._launch(order)

    async def submit_iceberg(
        self,
        symbol: str,
        side: str,
        total_quantity: float,
        peak_size: float,
        refill_delay_seconds: float = 0.5,
        strategy_id: str = "unknown",
    ) -> str:
        """Submit an Iceberg order. Returns algo_id."""
        order = IcebergOrder(
            symbol=symbol,
            side=side,
            total_quantity=total_quantity,
            peak_size=peak_size,
            refill_delay_seconds=refill_delay_seconds,
            strategy_id=strategy_id,
            broker_submit_fn=self._broker_submit,
        )
        return await self._launch(order)

    async def submit_auto(
        self,
        symbol: str,
        side: str,
        total_quantity: float,
        strategy_id: str = "unknown",
    ) -> str | None:
        """
        Automatically select and submit the appropriate algo based on order size.

        Returns algo_id if an algo was used, None if the order should be
        submitted as a plain market order.
        """
        if total_quantity >= self.ICEBERG_THRESHOLD:
            logger.info(
                "AlgoOrderManager: auto-selecting Iceberg for %.2f lots (%s %s)",
                total_quantity,
                side,
                symbol,
            )
            return await self.submit_iceberg(
                symbol=symbol,
                side=side,
                total_quantity=total_quantity,
                peak_size=self.DEFAULT_ICEBERG_PEAK,
                strategy_id=strategy_id,
            )
        elif total_quantity >= self.LARGE_ORDER_THRESHOLD:
            logger.info(
                "AlgoOrderManager: auto-selecting TWAP for %.2f lots (%s %s)",
                total_quantity,
                side,
                symbol,
            )
            return await self.submit_twap(
                symbol=symbol,
                side=side,
                total_quantity=total_quantity,
                duration_seconds=self.DEFAULT_TWAP_DURATION,
                num_slices=self.DEFAULT_TWAP_SLICES,
                strategy_id=strategy_id,
            )
        return None  # use plain market order

    def cancel(self, algo_id: str) -> bool:
        """Cancel an active algo order. Returns True if found and cancelled."""
        order = self._active.get(algo_id)
        if order:
            order.cancel()
            return True
        return False

    def get_status(self, algo_id: str) -> dict[str, Any] | None:
        """Return status dict for an active or completed algo order."""
        order = self._active.get(algo_id)
        if order:
            return {
                "algo_id": algo_id,
                "status": order.status.value,
                "filled": order.filled_quantity,
                "total": order.total_quantity,
                "remaining": order.remaining_quantity,
                "avg_price": order.avg_fill_price,
                "child_orders": len(order.child_orders),
            }
        report = self._completed.get(algo_id)
        if report:
            return {
                "algo_id": algo_id,
                "status": report.status.value,
                "filled": report.filled_quantity,
                "total": report.total_quantity,
                "avg_price": report.avg_fill_price,
                "duration_s": report.duration_seconds,
                "child_orders": report.num_child_orders,
            }
        return None

    def get_all_active(self) -> dict[str, dict[str, Any]]:
        """Return status for all active algo orders."""
        return {aid: self.get_status(aid) for aid in self._active}

    async def _launch(self, order: AlgoOrder) -> str:
        """Launch an algo order in a background task."""
        self._active[order.algo_id] = order
        task = asyncio.create_task(
            self._run_order(order),
            name=f"algo_{type(order).__name__}_{order.algo_id}",
        )
        self._tasks[order.algo_id] = task
        logger.info(
            "AlgoOrderManager: launched %s %s (id=%s)",
            type(order).__name__,
            order.symbol,
            order.algo_id,
        )
        return order.algo_id

    async def _run_order(self, order: AlgoOrder) -> None:
        """Run an algo order and move it to completed on finish."""
        try:
            report = await order.run()
            self._completed[order.algo_id] = report
        except Exception as exc:
            logger.error("AlgoOrderManager: order %s failed: %s", order.algo_id, exc)
        finally:
            self._active.pop(order.algo_id, None)
            self._tasks.pop(order.algo_id, None)


# ── Module-level singleton ────────────────────────────────────────────────────

_algo_manager: AlgoOrderManager | None = None


def get_algo_manager() -> AlgoOrderManager:
    """Return the module-level AlgoOrderManager singleton."""
    global _algo_manager
    if _algo_manager is None:
        _algo_manager = AlgoOrderManager()
    return _algo_manager
